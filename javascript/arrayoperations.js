weekdays.unshift("sunday")  //to add new items to the start  of an array
console.log(weekdays);

console.log('------------------------------------------------');

weekdays.pop();
console.log(weekdays);

console.log('------------------------------------------------');

weekdays.shift()
console.log(weekdays);

